/**
 * Retorna os artefatos arqueológicos correlacionados com o dia ou período de leitura
 */
export function getArtifactsForDay(
  dayNumber: number,
  periodId?: string,
  passages?: Array<{ book: string; reference: string }>
): ArchaeologicalArtifact[] {
  // Mapeamentos específicos por dia / livro / período
  const passageBooks = (passages || []).map(p => p.book.toLowerCase());

  // Jesus / Evangelhos / Julgamento
  if (periodId === 'gospels' || (dayNumber >= 296 && dayNumber <= 335)) {
    if (dayNumber >= 325) {
      return [
        MAJOR_ARCHAEOLOGICAL_ARTIFACTS.find(a => a.id === 'caiaphas-ossuary')!,
        MAJOR_ARCHAEOLOGICAL_ARTIFACTS.find(a => a.id === 'pilate-stone')!
      ].filter(Boolean);
    }
    return [
      MAJOR_ARCHAEOLOGICAL_ARTIFACTS.find(a => a.id === 'pilate-stone')!,
      MAJOR_ARCHAEOLOGICAL_ARTIFACTS.find(a => a.id === 'dead-sea-scrolls')!
    ].filter(Boolean);
  }

  // Igreja Primitiva / Atos / Epístolas / Apocalipse
  if (periodId === 'early-church' || dayNumber >= 336) {
    if (dayNumber >= 355) {
      return [
        MAJOR_ARCHAEOLOGICAL_ARTIFACTS.find(a => a.id === 'arch-of-titus')!
      ];
    }
    return [
      MAJOR_ARCHAEOLOGICAL_ARTIFACTS.find(a => a.id === 'erastus-inscription')!,
      MAJOR_ARCHAEOLOGICAL_ARTIFACTS.find(a => a.id === 'arch-of-titus')!
    ].filter(Boolean);
  }

  // Pós-Exílio / Retorno / Esdras / Neemias / Ester
  if (periodId === 'post-exile' || (dayNumber >= 276 && dayNumber <= 295)) {
    return [
      MAJOR_ARCHAEOLOGICAL_ARTIFACTS.find(a => a.id === 'cyrus-cylinder')!
    ];
  }

  // Cativeiro Babilônico / Ezequiel / Daniel / Jeremias 39-52
  if (periodId === 'exile' || (dayNumber >= 246 && dayNumber <= 275)) {
    return [
      MAJOR_ARCHAEOLOGICAL_ARTIFACTS.find(a => a.id === 'lachish-letters')!,
      MAJOR_ARCHAEOLOGICAL_ARTIFACTS.find(a => a.id === 'cyrus-cylinder')!
    ].filter(Boolean);
  }

  // Reino Dividido / Profetas Pré-Exílicos / Isaías / Ezequias / Acabe
  if (periodId === 'divided-kingdom' || (dayNumber >= 166 && dayNumber <= 245)) {
    if (dayNumber >= 200 && dayNumber <= 225) {
      return [
        MAJOR_ARCHAEOLOGICAL_ARTIFACTS.find(a => a.id === 'sennacherib-prism')!,
        MAJOR_ARCHAEOLOGICAL_ARTIFACTS.find(a => a.id === 'siloam-inscription')!
      ].filter(Boolean);
    }
    if (dayNumber >= 226) {
      return [
        MAJOR_ARCHAEOLOGICAL_ARTIFACTS.find(a => a.id === 'lachish-letters')!,
        MAJOR_ARCHAEOLOGICAL_ARTIFACTS.find(a => a.id === 'ketef-hinnom-scrolls')!
      ].filter(Boolean);
    }
    return [
      MAJOR_ARCHAEOLOGICAL_ARTIFACTS.find(a => a.id === 'tel-dan-stele')!,
      MAJOR_ARCHAEOLOGICAL_ARTIFACTS.find(a => a.id === 'black-obelisk-shalmaneser')!
    ].filter(Boolean);
  }

  // Reino Unido / Davi / Salomão
  if (periodId === 'united-kingdom' || (dayNumber >= 106 && dayNumber <= 165)) {
    return [
      MAJOR_ARCHAEOLOGICAL_ARTIFACTS.find(a => a.id === 'tel-dan-stele')!
    ];
  }

  // Conquista / Juízes / Josué
  if (periodId === 'conquest-judges' || (dayNumber >= 76 && dayNumber <= 105)) {
    return [
      MAJOR_ARCHAEOLOGICAL_ARTIFACTS.find(a => a.id === 'merneptah-stele')!
    ];
  }

  // Êxodo / Peregrinação / Moisés
  if (periodId === 'exodus-wilderness' || (dayNumber >= 27 && dayNumber <= 75)) {
    return [
      MAJOR_ARCHAEOLOGICAL_ARTIFACTS.find(a => a.id === 'merneptah-stele')!,
      MAJOR_ARCHAEOLOGICAL_ARTIFACTS.find(a => a.id === 'ketef-hinnom-scrolls')!
    ].filter(Boolean);
  }

  // Criação / Patriarcas / Jó / Abraão
  return [
    MAJOR_ARCHAEOLOGICAL_ARTIFACTS.find(a => a.id === 'hammurabi-code')!
  ];
}
