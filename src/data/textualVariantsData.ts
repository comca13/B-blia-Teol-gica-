export const getTextualVariantsForPassage = (bookName: string, chapter: number, verse?: number): TextualVariant[] => {
  if (!bookName) return [];
  const normalizedBook = bookName.toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "");

  return TEXTUAL_VARIANTS_CATALOG.filter(variant => {
    const refLower = variant.verseReference.toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "");
    
    // Check if book matches
    const matchesBook = refLower.includes(normalizedBook) || 
      (normalizedBook.includes('marcos') && refLower.includes('marcos')) ||
      (normalizedBook.includes('joao') && refLower.includes('joao')) ||
      (normalizedBook.includes('lucas') && refLower.includes('lucas')) ||
      (normalizedBook.includes('romanos') && refLower.includes('romanos')) ||
      (normalizedBook.includes('timoteo') && refLower.includes('timoteo')) ||
      (normalizedBook.includes('isaias') && refLower.includes('isaias')) ||
      (normalizedBook.includes('mateus') && refLower.includes('mateus')) ||
      (normalizedBook.includes('genesis') && refLower.includes('genesis')) ||
      (normalizedBook.includes('exodo') && refLower.includes('exodo'));

    if (!matchesBook) return false;

    // Check if chapter matches
    const chapterPattern = new RegExp(`\\b${chapter}:`);
    if (!chapterPattern.test(variant.verseReference)) return false;

    // If specific verse provided, test verse range
    if (verse !== undefined) {
      const match = variant.verseReference.match(/:(\d+)(?:[–-](\d+))?/);
      if (match) {
        const start = parseInt(match[1], 10);
        const end = match[2] ? parseInt(match[2], 10) : start;
        return verse >= start && verse <= end;
      }
    }

    return true;
  });
};

export const getTextualVariantsForDay = (day: number, passages?: Array<{ book: string; reference: string }>): TextualVariant[] => {
  if (!passages || passages.length === 0) {
    // Fallback por dia para os textos clássicos
    if (day >= 300 && day <= 325) { // Evangelhos
      return [TEXTUAL_VARIANTS_CATALOG[0], TEXTUAL_VARIANTS_CATALOG[1], TEXTUAL_VARIANTS_CATALOG[3], TEXTUAL_VARIANTS_CATALOG[7]];
    }
    if (day >= 326 && day <= 355) { // Epístolas
      return [TEXTUAL_VARIANTS_CATALOG[2], TEXTUAL_VARIANTS_CATALOG[4], TEXTUAL_VARIANTS_CATALOG[5]];
    }
    if (day >= 200 && day <= 240) { // Isaías
      return [TEXTUAL_VARIANTS_CATALOG[6]];
    }
    if (day <= 30) { // Gênesis / Êxodo
      return [TEXTUAL_VARIANTS_CATALOG[8], TEXTUAL_VARIANTS_CATALOG[9]];
    }
    return [];
  }

  const results: TextualVariant[] = [];
  const addedIds = new Set<string>();

  for (const passage of passages) {
    const bookName = passage.book;
    // Extrai número do capítulo da referência (ex: "16", "8", "7:53-8:11", "53:1-12")
    const match = passage.reference.match(/^(\d+)/);
    const chapter = match ? parseInt(match[1], 10) : 1;

    const variants = getTextualVariantsForPassage(bookName, chapter);
    for (const v of variants) {
      if (!addedIds.has(v.id)) {
        addedIds.add(v.id);
        results.push(v);
      }
    }
  }

  return results;
};
